/** Generates SOURCES.md, the fact table in DATA_GAPS.md and HINDI_REVIEW.md from the data files. */
import { readFileSync, writeFileSync } from 'node:fs';
import { COPY, FACT_LIST, QA } from '../src/data';
import { formatValue } from '../src/domain/format';
import { STAFF_PREFIXES } from '../src/domain/template';

const show = (v: number | string | null, unit?: string) => (v === null ? '(none)' : formatValue(v, unit).replace(/\|/g, '/'));
const where = (f: (typeof FACT_LIST)[number]) => (f.url ? `[${f.source}](${f.url})` : `${f.source}: ${f.doc}`);

const byStatus = (s: string) => FACT_LIST.filter((f) => f.status === s);
let src = `# Sources\n\nGenerated from \`src/data/facts.json\` by \`npm run data:docs\`. Do not edit by hand.\n\n`;
src += `${FACT_LIST.length} facts: ${byStatus('verified').length} verified against a published source, ${byStatus('from-team-research').length} from team research, ${byStatus('needs-verification').length} needing verification.\n\n`;
src += `| Fact id | What | Value | Source | Retrieved | Status |\n|---|---|---|---|---|---|\n`;
for (const f of FACT_LIST) src += `| \`${f.id}\` | ${f.label} | ${show(f.value, f.unit)} | ${where(f)} | ${f.retrieved} | ${f.status} |\n`;
writeFileSync('SOURCES.md', src);

const MARK = '<!-- generated:facts -->';
const gapsHead = readFileSync('DATA_GAPS.md', 'utf8').split(MARK)[0]!;
let gaps = `${gapsHead}${MARK}\n\n## Every fact marked \`needs-verification\`\n\nGenerated by \`npm run data:docs\`.\n\n| Fact id | What | Value shown | Why it is flagged |\n|---|---|---|---|\n`;
for (const f of byStatus('needs-verification')) gaps += `| \`${f.id}\` | ${f.label} | ${show(f.value, f.unit)} | ${f.note ?? f.doc ?? f.source} |\n`;
writeFileSync('DATA_GAPS.md', gaps);

let hi = `# Hindi review\n\nEvery Hindi string in the prototype, for a native speaker to check. Generated by \`npm run data:docs\`.\n\n**Status: written by the build, not yet reviewed by a native speaker.**\n\nSlots in braces (\`{f:...}\`, \`{c:...}\`, \`{n:...}\`, \`{name}\`) are filled in at run time and must be kept.\n\n## Interface strings\n\n| Key | English | Hindi | OK? |\n|---|---|---|---|\n`;
const esc = (s: string) => s.replace(/\|/g, '\\|');
for (const [k, en] of Object.entries(COPY.en)) {
  if (STAFF_PREFIXES.some((p) => k.startsWith(p))) continue;
  hi += `| \`${k}\` | ${esc(en)} | ${esc(COPY.hi[k] ?? '')} |  |\n`;
}
hi += `\n## Q&A library\n\n| Intent | English answer | Hindi answer | Hindi question variants | OK? |\n|---|---|---|---|---|\n`;
for (const q of QA) hi += `| \`${q.id}\` | ${esc(q.a.en)} | ${esc(q.a.hi)} | ${esc(q.q.hi.join(' / '))} |  |\n`;
writeFileSync('HINDI_REVIEW.md', hi);
console.log('Wrote SOURCES.md, DATA_GAPS.md, HINDI_REVIEW.md');
